        <h3>Rule 2: Quotient of Powers</h3>
        <p><strong>Rule:</strong> Subtract exponents when dividing same base.<br>
        Ex: y⁶ ÷ y² = y⁴</p>

        <h3>Rule 3: Power of a Power</h3>
        <p><strong>Rule:</strong> Multiply exponents.<br>
        Ex: (x³)² = x⁶</p>

        <h3>Rule 4: Power of a Product</h3>
        <p><strong>Rule:</strong> Distribute exponent.<br>
        Ex: (3x)² = 9x²</p>

        <h3>Rule 5: Zero Exponent</h3>
        <p><strong>Rule:</strong> Any nonzero base⁰ = 1.<br>
        Ex: x⁰ = 1</p>

        <h3>Rule 6: Negative Exponents</h3>
        <p><strong>Rule:</strong> Negative exponent = reciprocal.<br>
        Ex: x⁻³ = 1/x³</p>

